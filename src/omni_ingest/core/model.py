"""Pydantic data models for knowledge items, contexts, and results."""

from abc import ABC, abstractmethod
from enum import Enum
from pathlib import Path
from typing import Any, Generic, TypeVar, final
from uuid import UUID, uuid4

from fastmcp.mcp_config import MCPServerTypes
from pydantic import AnyUrl, BaseModel, ConfigDict, Field
from pydantic_ai import Agent
from pydantic_ai.models import KnownModelName

from .config import settings


class StepStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    SUCCESS = "success"
    FAILURE = "failure"
    SKIPPED = "skipped"


class ResolvedResource(BaseModel):
    uri: str = Field(...)
    content: str = Field(...)
    metadata: dict[str, Any] = Field(default_factory=dict)

type Resource = ResolvedResource | AnyUrl | Path


class KnowledgeItem(BaseModel):
    """
    Represents a discrete unit of information within the framework.

    A KnowledgeItem serves as a container for processed data, such as
    text segments, audio transcripts, or structured metadata. It is the primary
    entity processed and transformed throughout the ingestion pipeline.
    """

    model_config = ConfigDict(from_attributes=True, populate_by_name=True)
    id: UUID = Field(default_factory=uuid4, description="Unique identifier for the knowledge item")
    tenant_id: UUID | None = Field(None, description="Identifier for the associated tenant or organization")
    domain_profile: str = Field("default", description="Categorization label for the data domain")
    modality: str = Field("text", description="Data format", examples=["text", "audio", "image"])
    source_uri: str | None = Field(None, description="Origin URI of the raw data")
    title: str | None = Field(None, description="Human-readable title for the item")
    content: str = Field("", description="The primary data content of the item")
    description: str | None = Field(None, description="A brief summary of the item content")
    embeddings: list[dict[str, Any]] | None = Field(None, description="Vector representations for semantic search operations")
    structured_views: dict[str, Any] = Field(default_factory=dict, description="Organized data representations")
    lineage: dict[str, Any] = Field(default_factory=dict, description="Metadata trace documenting the item's creation and transformation history")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Arbitrary key-value pairs for additional contextual information")


class StepResult(BaseModel):
    """Result of an individual agentic step."""

    status: StepStatus = Field(..., description="The completion status of the step")
    output_paths: dict[str, str] = Field(default_factory=dict, description="Paths to any artifacts generated by the step")
    error: str | None = Field(None, description="Error message if the step failed")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Step-specific execution metadata")
    items: list[KnowledgeItem] = Field(default_factory=list, description="Knowledge items produced or modified by the step")


ResourceT = TypeVar("ResourceT", bound=Resource)
class IngestionContext(BaseModel, Generic[ResourceT]):  # noqa: UP046
    """
    Maintains state and shared metadata across a single ingestion pipeline execution.

    The IngestionContext object facilitates communication between sequential
    processing steps by carrying operational state, configuration parameters,
    and the current set of KnowledgeItems.
    """

    model_config = ConfigDict(from_attributes=True, populate_by_name=True)
    run_id: UUID = Field(default_factory=uuid4, description="Unique identifier for the current pipeline run")
    tenant_id: UUID = Field(default_factory=uuid4, description="Identifier for the active tenant")
    resource: ResourceT = Field(..., description="...")
    domain_profile: str = Field("default", description="The configuration profile being executed")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Shared state or context across steps")
    items: list[KnowledgeItem] = Field(default_factory=list, description="The working set of knowledge items")
    store: Any = Field(None, description="Reference to a storage engine or backend")


class Step(ABC):
    @abstractmethod
    async def run(self, ctx: IngestionContext[ResolvedResource]) -> StepResult:
        """Executes the specific logic for this ingestion step."""
        ...


class AgentMixin:
    model: KnownModelName | str = Field(settings.default_chat_completion_model, description="Model to use for this step")
    toolsets: list[str] = Field(default_factory=list, description="Toolsets to enable for the agent")

    @final
    def _agent(self, ctx: IngestionContext[Any]) -> Agent:
        from ..core.pipeline import PIPELINE_RUNNERS
        tool_vendors = PIPELINE_RUNNERS[ctx.run_id].toolsets
        missing = [ts for ts in self.toolsets if ts not in tool_vendors]
        if missing:
            raise ValueError(f"Toolsets not configured in context: {missing}")
        return Agent(self.model, toolsets=[tool_vendors[k] for k in self.toolsets])


class StepConfig(BaseModel):
    agent: str = Field(..., description="The registry name of the agent to execute")
    config: dict[str, Any] = Field(default_factory=dict, description="Step-specific configuration parameters")


class PipelineConfig(BaseModel):
    """Configuration for a complete ingestion pipeline."""

    pipeline_id: str | None = Field(None, description="Identifier for the pipeline template")
    domain_profile: str = Field("default", description="Domain profile name")
    input_modality: str | None = Field(None, description="Expected input modality", examples=["text", "document", "audio"])
    description: str | None = Field(None, description="Purpose of this pipeline")
    store: dict[str, Any] = Field(default_factory=dict, description="Configuration for the metadata store")
    graph_store: dict[str, Any] = Field(default_factory=dict, description="Configuration for the graph store")
    steps: list[StepConfig] = Field(..., description="Ordered list of agentic steps to execute")
    tool_vendors: dict[str, MCPServerTypes] = Field(default_factory=dict, description="Configured tool vendors available for agents")
